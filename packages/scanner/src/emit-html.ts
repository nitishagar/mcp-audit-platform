import { SEVERITY_RANK, type Finding } from "./schema.js";
import type { AuditResult } from "./runner.js";
import { ruleMeta } from "./rules.js";

/**
 * A6: print-ready HTML report (D-10(a) — the pack ships free in the CLI).
 * Self-contained: inline CSS, no JS, no external fetches; print CSS so
 * "Save as PDF" yields the board pack. Every dynamic string is escaped
 * (findings already redacted at construction — I4), and the emitter adds
 * no attributes from input, so a hostile tool name cannot inject markup.
 */

function esc(s: string): string {
  return s
    .replace(/&/g, "&amp;")
    .replace(/</g, "&lt;")
    .replace(/>/g, "&gt;")
    .replace(/"/g, "&quot;");
}

function severityClass(sev: string): string {
  // esc: runReport re-renders untrusted audit.json files — the severity must
  // never reach an attribute raw (A6 red-team Medium 2).
  return esc(`sev-${sev}`);
}

const EFFORT_RANK: Record<string, number> = { quick: 0, moderate: 1, deep: 2 };

function fails(result: AuditResult): Finding[] {
  return result.checks
    .flatMap((c) => c.findings.filter((f) => f.status === "fail"))
    .sort(
      (a, b) =>
        SEVERITY_RANK[b.severity] - SEVERITY_RANK[a.severity] ||
        (EFFORT_RANK[ruleMeta(a.checkId)?.effort ?? "moderate"] ?? 1) -
          (EFFORT_RANK[ruleMeta(b.checkId)?.effort ?? "moderate"] ?? 1) ||
        a.checkId.localeCompare(b.checkId) ||
        a.id.localeCompare(b.id),
    );
}

export function emitHtml(result: AuditResult): string {
  const allFails = fails(result);
  const counts: Record<string, number> = { critical: 0, high: 0, medium: 0, low: 0 };
  for (const f of allFails) counts[f.severity] = (counts[f.severity] ?? 0) + 1;
  const passed = result.checks.filter((c) => c.status === "pass").length;
  const inputUnass = result.checks.filter(
    (c) => c.status === "unassessable" && c.scope === "input",
  );
  const covUnass = result.checks.filter(
    (c) => c.status === "unassessable" && c.scope === "coverage",
  );
  const notApplicable = result.checks.filter((c) => c.status === "not_applicable");
  const top5 = allFails.slice(0, 5);

  const L: string[] = [];
  L.push(`<!doctype html>`);
  L.push(`<html lang="en">`);
  L.push(`<head>`);
  L.push(`<meta charset="utf-8">`);
  // Defense in depth: the report is JS-free by design (A6 red-team Low 6).
  L.push(
    `<meta http-equiv="Content-Security-Policy" content="default-src 'none'; style-src 'unsafe-inline'">`,
  );
  L.push(`<meta name="viewport" content="width=device-width, initial-scale=1">`);
  L.push(`<title>mcp-audit report</title>`);
  L.push(`<style>`);
  L.push(
    `:root { color-scheme: light; --ink:#1c2430; --muted:#5b6472; --line:#d9dee5; --accent:#1a4b8f; }`,
  );
  L.push(`* { box-sizing: border-box; }`);
  L.push(
    `body { font: 14px/1.55 -apple-system, "Segoe UI", sans-serif; color: var(--ink); margin: 0; padding: 40px; max-width: 900px; }`,
  );
  L.push(`h1 { font-size: 22px; margin: 0 0 4px; }`);
  L.push(
    `h2 { font-size: 16px; margin: 28px 0 8px; border-bottom: 1px solid var(--line); padding-bottom: 4px; }`,
  );
  L.push(`h3 { font-size: 13px; margin: 16px 0 6px; }`);
  L.push(`.muted { color: var(--muted); }`);
  L.push(`table { border-collapse: collapse; width: 100%; margin: 8px 0; }`);
  L.push(
    `th, td { border: 1px solid var(--line); padding: 6px 8px; text-align: left; vertical-align: top; font-size: 13px; }`,
  );
  L.push(
    `code { background: #f2f4f7; padding: 1px 4px; border-radius: 3px; font-size: 12px; word-break: break-all; }`,
  );
  L.push(
    `.badge { display: inline-block; font-weight: 700; font-size: 11px; padding: 1px 8px; border-radius: 10px; color: #fff; }`,
  );
  L.push(`.sev-critical { background: #8f1d1d; }`);
  L.push(`.sev-high { background: #b4430f; }`);
  L.push(`.sev-medium { background: #8a6d00; }`);
  L.push(`.sev-low { background: #4a5b70; }`);
  L.push(`.pagebreak { page-break-before: always; }`);
  L.push(
    `@media print { body { padding: 20mm; } h2 { page-break-after: avoid; } .pagebreak { page-break-before: always; } }`,
  );
  L.push(`@page { margin: 18mm; }`);
  L.push(`</style>`);
  L.push(`</head>`);
  L.push(`<body>`);

  // Cover
  L.push(`<h1>MCP Config Audit Report</h1>`);
  L.push(
    `<p class="muted">Generated by ${esc(result.tool)} ${esc(result.toolVersion)} · Framework: ${esc(result.framework)} · ${esc(new Date().toISOString().slice(0, 10))}</p>`,
  );
  L.push(`<table><tbody>`);
  L.push(
    `<tr><th>Critical</th><th>High</th><th>Medium</th><th>Low</th><th>Passed checks</th><th>Not applicable</th><th>Not determinable</th></tr>`,
  );
  L.push(
    `<tr><td>${counts.critical}</td><td>${counts.high}</td><td>${counts.medium}</td><td>${counts.low}</td><td>${passed}</td><td>${notApplicable.length}</td><td>${covUnass.length}</td></tr>`,
  );
  L.push(`</tbody></table>`);

  // 1-page exec summary
  L.push(`<h2>Executive summary</h2>`);
  if (allFails.length === 0) {
    L.push(
      `<p>No findings at the audit's severity floor. ${passed} check(s) passed; review the not-determinable appendix for what static analysis could not see.</p>`,
    );
  } else {
    L.push(
      `<p>${allFails.length} finding(s): ${counts.critical} critical, ${counts.high} high, ${counts.medium} medium, ${counts.low} low. Highest-priority items first:</p>`,
    );
    L.push(`<ol>`);
    for (const f of top5) {
      const meta = ruleMeta(f.checkId);
      L.push(
        `<li><strong>${esc(meta?.title ?? f.checkId)}</strong> — ${esc(f.detail.replace(/\s+/g, " ").slice(0, 240))}</li>`,
      );
    }
    L.push(`</ol>`);
  }
  L.push(
    `<p class="muted">This report is a static configuration analysis. It is not a penetration test; no live system was probed. Findings describe what the configuration shows — several server-side properties are listed as "not determinable" instead of guessed.</p>`,
  );

  // Prioritized fix checklist
  L.push(`<h2 class="pagebreak">Prioritized fix checklist</h2>`);
  if (allFails.length === 0) {
    L.push(`<p>Nothing to fix at this severity floor.</p>`);
  } else {
    L.push(
      `<table><thead><tr><th>#</th><th>Severity</th><th>Fix</th><th>Effort</th><th>Where</th></tr></thead><tbody>`,
    );
    allFails.forEach((f, idx) => {
      const meta = ruleMeta(f.checkId);
      L.push(
        `<tr><td>${idx + 1}</td><td><span class="badge ${severityClass(f.severity)}">${esc(f.severity)}</span></td>` +
          `<td><strong>${esc(meta?.title ?? f.checkId)}</strong> — ${esc(meta?.remediation ?? "")}<br><span class="muted">${esc(f.detail)}</span></td>` +
          `<td>${esc(meta?.effort ?? "moderate")}</td><td><code>${esc(f.pointer)}</code></td></tr>`,
      );
    });
    L.push(`</tbody></table>`);
  }

  // Technical findings
  L.push(`<h2 class="pagebreak">Technical findings</h2>`);
  if (allFails.length === 0) {
    L.push(`<p>No technical findings.</p>`);
  } else {
    for (const f of allFails) {
      const meta = ruleMeta(f.checkId);
      L.push(
        `<h3><span class="badge ${severityClass(f.severity)}">${esc(f.severity)}</span> ${esc(f.checkId)} — ${esc(meta?.title ?? "")}</h3>`,
      );
      L.push(`<p><code>${esc(f.pointer)}</code> · finding <code>${esc(f.id)}</code></p>`);
      L.push(`<p>${esc(f.detail)}</p>`);
      if (meta) {
        L.push(`<p><strong>Why it matters:</strong> ${esc(meta.rationale)}</p>`);
        L.push(`<p><strong>Refs:</strong> ${esc(f.frameworkRefs.join(", "))}</p>`);
      }
    }
  }

  // Appendix: unassessable + not applicable
  L.push(`<h2 class="pagebreak">Appendix: what static analysis could not assess</h2>`);
  if (inputUnass.length > 0) {
    L.push(`<h3>Input problems (these checks did not run)</h3><ul>`);
    for (const c of inputUnass) {
      for (const f of c.findings)
        L.push(`<li><strong>${esc(f.checkId)}</strong> — ${esc(f.detail)}</li>`);
    }
    L.push(`</ul>`);
  }
  if (covUnass.length > 0) {
    L.push(`<h3>Not determinable from this input</h3><ul>`);
    for (const c of covUnass) {
      for (const f of c.findings)
        L.push(`<li><strong>${esc(f.checkId)}</strong> — ${esc(f.detail)}</li>`);
    }
    L.push(`</ul>`);
  }
  if (notApplicable.length > 0) {
    L.push(`<h3>Not applicable</h3><ul>`);
    for (const c of notApplicable)
      L.push(`<li>${esc(c.checkId)} — its subject is absent from this input</li>`);
    L.push(`</ul>`);
  }
  if (result.warnings.length > 0) {
    L.push(`<h3>Warnings</h3><ul>`);
    for (const w of result.warnings) L.push(`<li>${esc(w)}</li>`);
    L.push(`</ul>`);
  }

  // Methodology + disclaimer
  L.push(`<h2>Methodology</h2>`);
  L.push(
    `<p class="muted">Deterministic offline static analysis of the provided configuration and tool-schema files (checks: ${esc(result.checks.map((c) => c.checkId).join(", "))}). Severity derives from the pinned OWASP MCP Top 10 v2025-beta category mapping; advisory matches come from the bundled OSV snapshot. No network access, no live probing, no exploitation.</p>`,
  );
  L.push(`<p class="muted">Static analysis only — not a penetration test.</p>`);
  L.push(`</body></html>`);
  return `${L.join("\n")}\n`;
}
